package practice.mypackage;

public class Assignment_4 {

	public static void main(String[] args) {
		
		// Declare and initialize two numbers
        int num1 = 20;
        int num2 = 6;

        // 1. Addition (+)
        int sum = num1 + num2;
        
        // 2. Subtraction (-)
        int difference = num1 - num2;
        
        // 3. Multiplication (*)
        int product = num1 * num2;
        
        // 4. Division (/) - Gives the quotient (how many times it goes in)
        int quotient = num1 / num2;
        
        // 5. Modulus (%) - Gives the remainder left over
        int remainder = num1 % num2;

        // --- Printing the results ---
        System.out.println("Numbers are: " + num1 + " and " + num2);
        System.out.println("Addition  = " + sum);
        System.out.println("Subtraction  = " + difference);
        System.out.println("Multiplication  = " + product);
        System.out.println("Division  = " + quotient);  
        System.out.println("Modulus/Remainder = " + remainder); 

		
		
	}

}
