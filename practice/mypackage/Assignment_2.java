package practice.mypackage;

public class Assignment_2 {

	public static void main(String[] args) {
		
		
		        // 1. Whole Numbers (Integers)
		        byte smallNumber = 100;                 
		        short mediumNumber = 30000;           
		        int regularNumber = 150000;            
		        long largeNumber = 9876543210L;       

		        // 2. Decimal Numbers (Floating Points)
		        float decimalFloat = 5.99f;            
		        double decimalDouble = 10.456789;      

		        // 3. Characters and Text
		        char singleLetter = 'A';             
		        String textMessage = "Hello GroTechMinds";     

		        // 4. Yes / No Choices
		        boolean isJavaFun = true;           

		        // --- Printing the variables to see their values 
		        System.out.println("Byte Value: " + smallNumber);
		        System.out.println("Short Value: " + mediumNumber);
		        System.out.println("Int Value: " + regularNumber);
		        System.out.println("Long Value: " + largeNumber);
		        System.out.println("Float Value: " + decimalFloat);
		        System.out.println("Double Value: " + decimalDouble);
		        System.out.println("Char Value: " + singleLetter);
		        System.out.println("String Value: " + textMessage);
		        System.out.println("Boolean Value: " + isJavaFun);
		    }	
	
}
